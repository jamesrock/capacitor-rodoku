const rotate = (values, rotate) => {
	return rotators[rotate].map((item) => values[item]);
};

const rotateCoords = (values, rotate) => {
	return values.map((box) => {
		return box.map((coord) => {
			return coordMaps[rotate][coord];
		});
	});
};

const augment = (target, difficulty) => {
  let newPuzzles = [];
  target.forEach((puzzle) => {
    newPuzzles = newPuzzles.concat([0, 1, 2, 3].map((rotation) => {
      return [
        rotateCoords(puzzle[0], rotation),
        rotate(puzzle[1], rotation),
        rotate(puzzle[2], rotation),
        difficulty
      ];
    }));
  });
  return newPuzzles;
};

